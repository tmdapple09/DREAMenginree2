function normalizeRel(relPath) {
  return relPath.split(path.sep).join('/');
}

function removeExt(relPath) {
  const ext = path.extname(relPath);
  return ext ? relPath.slice(0, -ext.length) : relPath;
}

function startsWithAny(relPath, prefixes) {
  return prefixes.some((prefix) => relPath.startsWith(prefix));
}

function pathContainsAny(relPath, segments) {
  return segments.some((segment) => relPath.includes(segment));
}

function inferEngine(relPath) {
  if (relPath.startsWith('engins/CodeEngin/')) return 'CodeEngin';

  if (
    relPath.startsWith('lib/gameengin/') ||
    relPath.startsWith('components/gameengin/') ||
    relPath.startsWith('components/games/')
  ) {
    return 'GameEngin';
  }

  if (relPath === 'components/daydream/dream.LabDreamIDE.tsx') return 'LabEngin';
  if (relPath === 'components/daydream/dream.CodeDreamIDE.tsx') return 'CodeEngin';
  if (relPath.startsWith('daydreams/music/')) return 'StarmakerEngin';
  if (relPath.startsWith('components/dreamengin/')) return 'DrEamsEngin';
  if (relPath.startsWith('components/forge/') || relPath.startsWith('lib/forge-ngn/')) return 'ForgeNGN';

  if (relPath.startsWith('lib/dreamr/') || relPath.startsWith('app/dreamr/')) return 'DreamR';
  if (relPath.startsWith('lib/dreamdm/') || relPath.startsWith('dreamdmbar/')) return 'DreamDMBar';
  if (relPath.startsWith('lib/home-buttons/') || pathContainsAny(relPath, ['HomeDream', 'homedream'])) return 'HomeDream';
  if (relPath.startsWith('lib/dreams/') || relPath.startsWith('lib/dream-window/') || relPath.startsWith('lib/widgets/')) return 'DreamSurface';

  return 'Universal';
}

async function walkDirectory(absDir) {
  const files = [];

  async function visit(currentDir) {
    let entries;

    try {
      entries = await fs.readdir(currentDir, { withFileTypes: true });
    } catch {
      return;
    }

    await Promise.all(entries.map(async (entry) => {
      if (entry.name.startsWith('.')) return;

      const absPath = path.join(currentDir, entry.name);
      const relPath = normalizeRel(path.relative(ROOT, absPath));

      if (entry.isDirectory()) {
        if (SCAN_EXCLUDE.has(entry.name)) return;
        await visit(absPath);
        return;
      }

      files.push(relPath);
    }));
  }

  await visit(absDir);
  return files;
}

