async function detectExports(relPath) {
  const ext = path.extname(relPath);

  if (!['.ts', '.tsx', '.mts', '.cts', '.js', '.mjs', '.cjs'].includes(ext)) {
    return [];
  }

  try {
    const source = await fs.readFile(path.join(ROOT, relPath), 'utf8');
    const exported = new Set();

    if (/\bexport\s+default\b/m.test(source)) {
      exported.add('default');
    }

    const namedDecl = source.matchAll(/\bexport\s+(?:const|let|var|function|class|type|interface|enum)\s+([A-Za-z_$][\w$]*)/g);

    for (const match of namedDecl) {
      const name = match[1];
      if (name) exported.add(name);
    }

    const namedBlock = source.matchAll(/\bexport\s*\{([^}]+)\}/g);

    for (const block of namedBlock) {
      const segment = block[1];
      if (!segment) continue;

      const names = segment
        .split(',')
        .map((item) => item.trim())
        .filter(Boolean);

      for (const name of names) {
        const asMatch = /\bas\s+([A-Za-z_$][\w$]*)$/.exec(name);

        if (asMatch?.[1]) {
          exported.add(asMatch[1]);
          continue;
        }

        const clean = name.replace(/^type\s+/, '').trim();
        if (clean) exported.add(clean);
      }
    }

    return Array.from(exported).sort((a, b) => a.localeCompare(b));
  } catch {
    return [];
  }
}

function classifySlot(relPath) {
  const isDeclarationFile = relPath.endsWith('.d.ts');
  const isTestLike = /\.((test|spec)\.(ts|tsx))$/.test(relPath);
  const isTs = relPath.endsWith('.ts') && !isDeclarationFile && !isTestLike;
  const isTsx = relPath.endsWith('.tsx') && !isTestLike;
  const isSql = relPath.endsWith('.sql');
  const isJson = relPath.endsWith('.json');
  const isMd = relPath.endsWith('.md');

  const isCode = isTs || isTsx;

  if (relPath.startsWith('coresurfaces/') && isCode) return 'core-surface';

  if (/^daydreams\/.+\/page\.tsx$/.test(relPath)) return 'route-surface';
  if (relPath.startsWith('daydreams/') && isCode) return 'daydream';

  if (
    startsWithAny(relPath, [
      'lib/dreamr/',
      'app/dreamr/',
      'components/dreamr/',
      'components/DreamR/',
    ]) && isCode
  ) {
    return 'dreamr';
  }

  if (
    startsWithAny(relPath, [
      'lib/dreamdm/',
      'dreamdmbar/',
      'components/dreamdm/',
      'components/DreamDM/',
      'components/dreamdmbar/',
      'components/DreamDMBar/',
    ]) && isCode
  ) {
    return 'dreamdmbar';
  }

  if (
    startsWithAny(relPath, [
      'lib/home-buttons/',
      'components/homedream/',
      'components/HomeDream/',
      'app/homedream/',
      'app/home/',
    ]) && isCode
  ) {
    return 'homedream';
  }

  if (
    startsWithAny(relPath, [
      'lib/dreams/',
      'lib/dream-window/',
      'lib/widgets/',
      'components/dreams/',
      'components/Dreams/',
      'components/dreamsurface/',
      'components/DreamSurface/',
      'app/dreams/',
    ]) && isCode
  ) {
    return 'dreamsurface';
  }

  if (relPath.startsWith('components/') && isCode) return 'surface';

  if (relPath.startsWith('app/') && isCode && !APP_ROUTE_SURFACE_EXCLUDES.has(relPath)) {
    return 'route-surface';
  }

  if (relPath.startsWith('engins/') && isCode) return 'engin';
  if (relPath.startsWith('lib/engins/') && isTs) return 'engine-ruleset';
  if (relPath.startsWith('src/dream/rulesets/')) return 'engine-ruleset';

  if (relPath.startsWith('lib/connectors/') && isTs) return 'connector';
  if (relPath.startsWith('lib/gameengin/brain/') && isJson) return 'brain-node';
  if (relPath.startsWith('lib/gameengin/brain/') && isMd) return 'brain-doc';
  if (relPath.startsWith('lib/gameengin/cartridges/')) return 'cartridge';
  if (/^public\/cartridges\/.+\/MANIFEST\.json$/.test(relPath)) return 'cartridge';
  if (relPath === 'agents/humanAI.persona.md' || /^agents\/humanAI\/personas\/[^/]+\.md$/.test(relPath)) return 'persona';
  if (relPath.startsWith('supabase/migrations/') && isSql) return 'migration';
  if (relPath.startsWith('build-memory/') && isJson) return 'memory';
  if (relPath.startsWith('dr-eams/')) return 'dr-eams-tool';
  if (relPath.startsWith('hooks/') && isTs) return 'hook';
  if (relPath.startsWith('lib/hooks/') && isTs) return 'hook';
  if (relPath.startsWith('lib/games/') && isTs) return 'engine-system';
  if (relPath.startsWith('lib/gameengin/') && isTs && !relPath.startsWith('lib/gameengin/brain/')) return 'engine-system';
  if (relPath.startsWith('lib/') && isTs) return 'engine-utility';

  return null;
}

function toRegistryId(relPath) {
  return removeExt(relPath);
}

function asImportLiteral(relPath) {
  const withoutSourceExtension = relPath.replace(/\.(ts|tsx|js|mjs|cjs)$/, '');
  return `@/${withoutSourceExtension}`;
}

function buildLoaderLine(entry) {
  const ext = path.extname(entry.path);
  const isDeclarationFile = entry.path.endsWith('.d.ts');
  const supportsImport = !isDeclarationFile && ['.ts', '.tsx', '.js', '.mjs', '.cjs', '.json'].includes(ext);

  if (supportsImport) {
    return `  ${JSON.stringify(entry.id)}: () => import(${JSON.stringify(asImportLiteral(entry.path))}),`;
  }

  return `  ${JSON.stringify(entry.id)}: async () => ({ default: ${JSON.stringify(entry.path)} }),`;
}

function buildGeneratedModule(name, entries) {
  const lines = [
    GENERATED_HEADER,
    '',
    `export const ${name} = {`,
    ...entries.map((entry) => buildLoaderLine(entry)),
    '};',
    '',
    `export type ${name[0].toUpperCase()}${name.slice(1)}Map = typeof ${name};`,
    '',
  ];

  return `${lines.join('\n')}`;
}

